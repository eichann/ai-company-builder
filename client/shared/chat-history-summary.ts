import type { ChatSession, ChatSessionSummary } from './chat-history'

/** Longest preview kept in a summary (the sidebar shows one truncated line). */
export const SUMMARY_PREVIEW_CHARS = 120

/** The sidebar's one-line preview: the last non-empty message, tool markers and runs of whitespace removed. */
export function sessionPreview(session: Pick<ChatSession, 'messages'>): string {
  for (let i = session.messages.length - 1; i >= 0; i--) {
    const message = session.messages[i]
    if (message.id === '1' || !message.content.trim()) continue
    // Clean only a bounded head: a reply can be tens of KB and only 120 characters are shown.
    return message.content.slice(0, SUMMARY_PREVIEW_CHARS * 8)
      .replace(/\[Tool:[^\]]*\]/g, '').replace(/\s+/g, ' ').trim().slice(0, SUMMARY_PREVIEW_CHARS)
  }
  return ''
}

/** Everything the session lists need, without the message bodies. */
export function summarizeSession(session: ChatSession): ChatSessionSummary {
  return {
    id: session.id,
    companyId: session.companyId,
    title: session.title,
    createdAt: session.createdAt,
    updatedAt: session.updatedAt,
    messageCount: session.messages.length,
    sent: session.messages.some(message => message.role === 'user'),
    preview: sessionPreview(session),
    ...(session.draftInput ? { draftInput: session.draftInput } : {}),
    ...(session.titleAutoGenerated !== undefined ? { titleAutoGenerated: session.titleAutoGenerated } : {}),
    ...(session.pinned !== undefined ? { pinned: session.pinned } : {}),
    ...(session.pinnedAt !== undefined ? { pinnedAt: session.pinnedAt } : {}),
    ...(session.revision !== undefined ? { revision: session.revision } : {}),
  }
}

/** Search normalisation shared by the sidebar (titles, drafts) and the store (message bodies). */
export function normalizeSearchText(text: string): string {
  return text.normalize('NFKC').toLocaleLowerCase()
}
