import type { AgentSession } from './agent'
import type { ChoicePromptRecord } from './choice-prompt'
import type { SteerRecord } from './steer'
import type { ReviewRecord } from './review-request'
export interface ChatSession {
  id: string
  companyId: string
  title: string
  messages: Array<{
    id: string
    role: 'user' | 'assistant'
    content: string
    timestamp: string
    thinking?: string
    images?: string[]
    referenceFiles?: string[]
    consultationReferences?: Array<{ id: string; title: string }>
    /** Choice prompts in this reply, how the member answered, and where (`at`: offset in `content`; `seq`: part index, orders records at the same `at`). */
    choicePrompts?: Array<ChoicePromptRecord & { at?: number; seq?: number }>
    /** Extra instructions the member sent while this reply was being written (`at`, `seq` as above). */
    steerInstructions?: Array<SteerRecord & { at?: number; seq?: number }>
    /** 「確認をお願いします」 requests in this reply (review-request.ts); shown after its text. */
    reviewRequests?: ReviewRecord[]
  }>
  createdAt: string
  updatedAt: string
  claudeSessionId?: string
  agentSession?: AgentSession | null
  draftInput?: string
  titleAutoGenerated?: boolean
  pinned?: boolean
  pinnedAt?: string
  writerId?: string
  writeSequence?: number
  revision?: number
}

export type ChatMetadataPatch = Partial<Pick<ChatSession,
  'title' | 'titleAutoGenerated' | 'pinned' | 'claudeSessionId' | 'agentSession'>>

export type ChatSaveResult =
  | { status: 'saved'; session: ChatSession }
  | { status: 'conflict'; session: ChatSession }
  | { status: 'deleted' }

/** What the renderer gets back from a save: the revision, not the whole stored conversation. */
export type ChatSaveReceipt =
  | { status: 'saved' | 'conflict'; revision: number }
  | { status: 'deleted' }

/** A session without its message bodies: what the session lists need (`chatHistory:getSummaries`). */
export interface ChatSessionSummary {
  id: string
  companyId: string
  title: string
  createdAt: string
  updatedAt: string
  /** Number of stored messages. */
  messageCount: number
  /** The member has sent at least one message (absent: treat as sent). */
  sent?: boolean
  /** One line from the last non-empty message, tool markers removed (≤120 characters). */
  preview: string
  draftInput?: string
  titleAutoGenerated?: boolean
  pinned?: boolean
  pinnedAt?: string
  revision?: number
}

export interface ChatHistoryChange {
  companyId: string
  /** The session that changed; absent when the whole company's history may have changed. */
  sessionId?: string
  /** `save` = messages / draft (the writing tab already has them), `patch` = title, pin or AI session, `delete`. */
  kind?: 'save' | 'patch' | 'delete'
  deletedSessionId?: string
}
