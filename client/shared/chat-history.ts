import type { DroppedRecordRef } from './record-drop'
import type { AgentSession } from './agent'
import type { ChoicePromptRecord } from './choice-prompt'
import type { SteerRecord } from './steer'
import type { ReviewRecord } from './review-request'
import type { PluginOperationCard } from './plugin-operations'
import type { ApprovalCardRef } from './approvals'
import type { MinutesBundleChoiceCard } from './minutes-app'
import type { DriveOverwriteCard } from './drive-overwrite'
import type { MailDraftCard } from './outbound-mail'
import type { StoredToolLine } from './tool-display'
import type { AppInstruction } from './app-instruction'
import type { SecondOpinionRecord } from './agents/second-opinion'
import type { FileLinkedPart } from './consultation-task'
export interface ChatSession {
  id: string
  companyId: string
  title: string
  messages: Array<{
    id: string
    role: 'user' | 'assistant'
    content: string
    timestamp: string
    thinking?: string
    images?: string[]
    referenceFiles?: string[]
    consultationReferences?: Array<{ id: string; title: string }>
    /** Choice prompts in this reply, how the member answered, and where (`at`: offset in `content`; `seq`: part index, orders records at the same `at`). */
    choicePrompts?: Array<ChoicePromptRecord & { at?: number; seq?: number }>
    /** Extra instructions the member sent while this reply was being written (`at`, `seq` as above). */
    steerInstructions?: Array<SteerRecord & { at?: number; seq?: number }>
    /** 「確認をお願いします」 requests in this reply (review-request.ts); shown after its text. */
    reviewRequests?: ReviewRecord[]
    /** Outside systems' writes (HubSpot) in this reply, with 「変更前の値を書き戻す」 (plugin-operations.ts); shown after its text. */
    pluginOperations?: PluginOperationCard[]
    /** Approval requests made or shown in this reply (approvals.ts): a reference; the card reads the request from the server. */
    approvals?: ApprovalCardRef[]
    /** 「どの案件の議事録ですか？」 cards in this reply (minutes-app.ts). */
    minutesDealChoices?: MinutesBundleChoiceCard[]
    /** The app's cards in the order the tools produced them (part ids), when a reply has two or more. */
    cardOrder?: string[]
    /** Mail drafts the AI made in this reply, drawn by the app with 「確かめて送る」 (outbound-mail.ts); shown after its text. */
    mailDrafts?: MailDraftCard[]
    /** 「〇〇さんの直しが入っています」 cards in this reply: 「上書きする」 / 「やめる」 for a Google document (drive-overwrite.ts). */
    driveOverwrites?: DriveOverwriteCard[]
    /** Files the AI made in this reply that the app linked to the consultation's task (consultation-task.ts): one line each. */
    linkedFiles?: FileLinkedPart[]
    /** 「もう一方の AI に聞く」: the other AI's answers in this reply, shown as folded quotes after its text (agents/second-opinion.ts). */
    secondOpinions?: SecondOpinionRecord[]
    /** Plain-Japanese labels of the app's tools this reply called, by tool name (tool-display.ts; the calls stay `[Tool: name]` markers in `content`). */
    toolLines?: Record<string, StoredToolLine>
    /** The app composed this message for the AI (app-instruction.ts): sent, never shown or previewed as the member's words. */
    appInstruction?: AppInstruction
    /** Records the member dropped on the input that went to the AI with this message (record-drop.ts): a line in its bubble. */
    droppedRecords?: DroppedRecordRef[]
  }>
  createdAt: string
  updatedAt: string
  claudeSessionId?: string
  agentSession?: AgentSession | null
  draftInput?: string
  titleAutoGenerated?: boolean
  pinned?: boolean
  pinnedAt?: string
  writerId?: string
  writeSequence?: number
  revision?: number
  /** The minutes record this consultation was started from (「<件名> のあと」, minutes-app.ts). */
  minutesId?: string
  /**
   * Its main topic (主な話題): the record 「相談する」 started it about (task-consult.ts), or the task the
   * AI made in it (consultation-task.ts). Metadata: changed through `patch`, kept by a save.
   */
  topicRecordId?: string
  /** The member took the topic off (「このやることから外す」): no topic is set by itself again. */
  topicDetached?: boolean
}

export type ChatMetadataPatch = Partial<Pick<ChatSession,
  'title' | 'titleAutoGenerated' | 'pinned' | 'claudeSessionId' | 'agentSession'>> & {
  /** A record id sets the topic (main only: the AI made a task); null takes it off and marks `topicDetached`. */
  topicRecordId?: string | null
}

export type ChatSaveResult =
  | { status: 'saved'; session: ChatSession }
  | { status: 'conflict'; session: ChatSession }
  | { status: 'deleted' }

/** What the renderer gets back from a save: the revision, not the whole stored conversation. */
export type ChatSaveReceipt =
  | { status: 'saved' | 'conflict'; revision: number }
  | { status: 'deleted' }

/** A session without its message bodies: what the session lists need (`chatHistory:getSummaries`). */
export interface ChatSessionSummary {
  id: string
  companyId: string
  title: string
  createdAt: string
  updatedAt: string
  /** Number of stored messages. */
  messageCount: number
  /** The member has sent at least one message (absent: treat as sent). */
  sent?: boolean
  /** One line from the last non-empty message, tool markers removed (≤120 characters). */
  preview: string
  draftInput?: string
  titleAutoGenerated?: boolean
  pinned?: boolean
  pinnedAt?: string
  revision?: number
  /** Its main topic (主な話題), when started from a record's 「相談する」. */
  topicRecordId?: string
}

export interface ChatHistoryChange {
  companyId: string
  /** The session that changed; absent when the whole company's history may have changed. */
  sessionId?: string
  /** `save` = messages / draft (the writing tab already has them), `patch` = title, pin or AI session, `delete`. */
  kind?: 'save' | 'patch' | 'delete'
  deletedSessionId?: string
}
