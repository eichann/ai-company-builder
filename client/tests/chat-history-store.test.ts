import { test, type TestContext } from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { ChatHistoryStore, atomicWrite } from '../electron/chat-history-store'
import type { ChatSession, ChatSaveResult } from '../shared/chat-history'

const company = 'company-1'
function session(id = 'chat-1', extra: Partial<ChatSession> = {}): ChatSession {
  return { id, companyId: company, title: '相談', createdAt: '2020-01-01T00:00:00Z',
    updatedAt: '2020-01-01T00:00:00Z', messages: [{ id: 'message-1', role: 'user', content: '相談内容', timestamp: '2020-01-01T00:00:00Z' }], ...extra }
}
function saved(result: ChatSaveResult): ChatSession {
  assert.equal(result.status, 'saved')
  if (result.status !== 'saved') throw new Error(result.status)
  return result.session
}
function fixture(t: TestContext) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'acb-history-test-'))
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }))
  return { dir, file: path.join(dir, `${company}.json`), store: new ChatHistoryStore(dir) }
}

test('legacy history survives reads, restart, and saves beyond 100 conversations and 30 days', t => {
  const { dir, file, store } = fixture(t)
  const sessions = Array.from({ length: 125 }, (_, i) => session(`chat-${i}`))
  fs.writeFileSync(file, JSON.stringify({ sessions }))
  const before = fs.readFileSync(file, 'utf8')
  assert.equal(store.list(company).length, 125)
  assert.equal(fs.readFileSync(file, 'utf8'), before)
  store.save(company, session('new'))
  assert.equal(new ChatHistoryStore(dir).list(company).length, 126)
  assert.equal(store.get(company, 'chat-0')?.messages[0].content, '相談内容')
})

test('same ID updates once, metadata edits do not overwrite messages or late manual titles', t => {
  const { store } = fixture(t)
  const first = saved(store.save(company, session()))
  const latest = saved(store.save(company, { ...first, messages: [...first.messages, { id: 'answer', role: 'assistant', content: '回答', timestamp: first.createdAt }] }))
  store.patch(company, first.id, { pinned: true })
  store.patch(company, first.id, { title: '手動変更', titleAutoGenerated: false })
  store.patch(company, first.id, { title: '遅延したAIタイトル', titleAutoGenerated: true })
  store.save(company, { ...latest, draftInput: '下書き' })
  const result = store.get(company, first.id)!
  assert.equal(store.list(company).length, 1)
  assert.equal(result.messages.length, 2)
  assert.equal(result.title, '手動変更')
  assert.equal(result.pinned, true)
  assert.equal(result.draftInput, '下書き')
})

test('stale writers cannot erase newer messages; in-flight same-writer flush is accepted', t => {
  const { store } = fixture(t)
  const first = saved(store.save(company, session('chat', { writerId: 'window-1', writeSequence: 1 })))
  const flush = saved(store.save(company, { ...first, revision: 0, writeSequence: 3, draftInput: '終了直前' }))
  assert.equal(store.save(company, { ...first, writeSequence: 2 }).status, 'conflict')
  assert.equal(store.save(company, { ...first, writerId: 'window-2', writeSequence: 9 }).status, 'conflict')
  assert.equal(store.get(company, 'chat')?.draftInput, '終了直前')
  assert.equal(store.save(company, { ...flush, writerId: 'window-2', writeSequence: 1 }).status, 'saved')
})

test('explicit deletion survives late saves and restarts; backup excludes deleted content', t => {
  const { dir, file, store } = fixture(t)
  const old = saved(store.save(company, session()))
  store.delete(company, old.id)
  store.delete(company, old.id)
  const reopened = new ChatHistoryStore(dir)
  assert.equal(reopened.save(company, old).status, 'deleted')
  assert.equal(reopened.patch(company, old.id, { pinned: true }), null)
  assert.deepEqual(reopened.list(company), [])
  assert.equal(JSON.parse(fs.readFileSync(`${file}.bak`, 'utf8')).sessions.length, 0)
})

test('corrupt history is never replaced with an empty or new history', t => {
  const { file, store } = fixture(t)
  fs.writeFileSync(file, '{broken')
  assert.throws(() => store.list(company))
  assert.throws(() => store.save(company, session()))
  assert.throws(() => store.delete(company, 'chat-1'))
  assert.equal(fs.readFileSync(file, 'utf8'), '{broken')
})

test('interrupted atomic replacement leaves original and removes temporary file', t => {
  const { file, dir } = fixture(t)
  fs.writeFileSync(file, 'original')
  t.mock.method(fs, 'renameSync', () => { throw new Error('simulated disk failure') })
  assert.throws(() => atomicWrite(file, 'replacement'), /simulated disk failure/)
  assert.equal(fs.readFileSync(file, 'utf8'), 'original')
  assert.deepEqual(fs.readdirSync(dir), [`${company}.json`])
})

test('invalid company and message identities are rejected without modifying storage', t => {
  const { dir, store } = fixture(t)
  assert.throws(() => store.list('../escape'))
  const invalid = session()
  invalid.messages.push(invalid.messages[0])
  assert.throws(() => store.save(company, invalid))
  assert.deepEqual(fs.readdirSync(dir), [])
})

test('restoring or pinning unchanged history does not make an old conversation look newly edited', t => {
  const { file, store } = fixture(t)
  fs.writeFileSync(file, JSON.stringify({ sessions: [session()] }))
  const existing = store.get(company, 'chat-1')!
  const restored = saved(store.save(company, { ...existing, writerId: 'restored', writeSequence: 1 }))
  store.patch(company, restored.id, { pinned: true })
  assert.equal(store.get(company, restored.id)?.updatedAt, existing.updatedAt)
})

test('provider session patches survive stale autosaves and restart', t => {
  const { dir, store } = fixture(t)
  const first = saved(store.save(company, session('provider-switch', { agentSession: { providerId: 'claude-code', id: 'claude-old' }, claudeSessionId: 'claude-old' })))
  store.patch(company, first.id, { agentSession: { providerId: 'codex', id: 'codex-new', modelId: 'model-a' } })
  store.save(company, { ...first, draftInput: '残す下書き' })
  const restored = new ChatHistoryStore(dir).get(company, first.id)!
  assert.equal(restored.agentSession?.providerId, 'codex')
  assert.equal(restored.agentSession?.id, 'codex-new')
  assert.equal(restored.draftInput, '残す下書き')
  store.patch(company, first.id, { agentSession: null })
  assert.equal(new ChatHistoryStore(dir).get(company, first.id)?.agentSession, null)
})
