import { useEffect, useRef, type MutableRefObject } from 'react'
import type { UIMessage } from 'ai'
import type { AuthMode } from '../../../../shared/agent'
import type { ChatServerClient } from '../chatServerClient'
import { titleTranscript } from '../chatSessionMessages'
import { patchChatSession } from '../../../features/chat/api'

export interface TitleGenerationOptions {
  status: string
  messages: UIMessage[]
  companyId: string | undefined
  chatServer: ChatServerClient
  appSessionIdRef: MutableRefObject<string | null>
  authModeRef: MutableRefObject<AuthMode>
  modelIdRef: MutableRefObject<string | undefined>
  /** Shared with useChatHistory: a restored or renamed conversation is not titled again. */
  titleGenerationDoneRef: MutableRefObject<boolean>
  customTitleRef: MutableRefObject<{ title: string; auto: boolean } | null>
  onTitleChange?: (title: string) => void
}

/**
 * One AI-generated title per conversation, asked for when the first reply
 * has finished streaming (greeting + one user message + one reply at least).
 * Failures keep the title taken from the first user message.
 */
export function useTitleGeneration(o: TitleGenerationOptions): void {
  const { status, messages, companyId } = o
  // Tracks previous status so we can detect "stream just finished" transitions
  const prevStatusRef = useRef<string>('ready')

  // Trigger one-shot title generation when the first AI response finishes streaming
  useEffect(() => {
    const wasStreaming = prevStatusRef.current === 'streaming' || prevStatusRef.current === 'submitted'
    const justFinished = wasStreaming && status === 'ready'
    prevStatusRef.current = status
    if (!justFinished) return
    if (o.titleGenerationDoneRef.current) return
    if (!companyId) return
    // Need at least: greeting + 1 user message + 1 assistant response
    if (messages.length < 3) return
    // Fire-and-forget; failures fall back to the truncated user message title
    generateAndSaveTitle()
    // eslint-disable-next-line react-hooks/exhaustive-deps -- runs on the status change only; `messages` and the callbacks change with every streamed token
  }, [status, messages.length, companyId])

  // Generate a concise title for the current session via the chat-server's title endpoint
  async function generateAndSaveTitle() {
    if (!companyId || !o.chatServer) return
    if (o.titleGenerationDoneRef.current) return

    // Skip greeting (first assistant message); take up to 6 subsequent messages
    const transcript = titleTranscript(messages)

    if (transcript.length < 2) return
    const targetSessionId = o.appSessionIdRef.current!
    o.titleGenerationDoneRef.current = true

    try {
      const data = await o.chatServer.generateTitle({ messages: transcript, authMode: o.authModeRef.current, modelId: o.modelIdRef.current })
      if (!data) return
      const newTitle = data.title?.trim()
      if (!newTitle) return

      const saved = await patchChatSession(companyId, targetSessionId, { title: newTitle, titleAutoGenerated: true })
      if (saved && o.appSessionIdRef.current === targetSessionId) {
        o.customTitleRef.current = { title: saved.title, auto: saved.titleAutoGenerated ?? false }
        o.onTitleChange?.(saved.title)
      }
    } catch (e) {
      console.error('Title generation failed:', e)
    }
  }
}
