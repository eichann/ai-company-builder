// A conversation the member left for another is removed only when nothing in it is
// worth keeping: deleting one with a draft, a sent message or a running turn loses work.
import { test } from 'node:test'
import assert from 'node:assert/strict'
import type { ChatSessionSummary } from '../../../shared/chat-history'
import { discardWhenLeft, type LeftConversation } from './model'

const blank: LeftConversation = { ready: true, hasMessages: false, draft: '', attachments: 0, busy: false }
const stored = (fields: Partial<ChatSessionSummary> = {}): ChatSessionSummary => ({
  id: 's1', companyId: 'c1', title: '新しい会話', createdAt: '2026-10-30T00:00:00Z', updatedAt: '2026-10-30T00:00:00Z',
  messageCount: 1, sent: false, preview: '', ...fields,
})

test('a blank conversation left for another is removed, saved or not', () => {
  assert.equal(discardWhenLeft(blank, undefined), true)
  assert.equal(discardWhenLeft(blank, stored()), true)
  // A draft typed and then erased leaves nothing either.
  assert.equal(discardWhenLeft({ ...blank, draft: '  \n' }, stored({ draftInput: '' })), true)
})

test('anything the member typed, attached or sent keeps the conversation', () => {
  assert.equal(discardWhenLeft({ ...blank, draft: '見積の' }, undefined), false)
  assert.equal(discardWhenLeft({ ...blank, attachments: 1 }, undefined), false)
  assert.equal(discardWhenLeft({ ...blank, hasMessages: true }, undefined), false)
  // The stored copy is checked too: a sent conversation is never deleted.
  assert.equal(discardWhenLeft(blank, stored({ sent: true })), false)
})

test('a renamed or pinned conversation is kept, like closing it keeps it', () => {
  assert.equal(discardWhenLeft(blank, stored({ title: '来期の計画', titleAutoGenerated: false })), false)
  assert.equal(discardWhenLeft(blank, stored({ pinned: true })), false)
})

test('a running turn, a waiting question or a conversation not restored yet is kept', () => {
  assert.equal(discardWhenLeft({ ...blank, busy: true }, undefined), false)
  assert.equal(discardWhenLeft({ ...blank, ready: false }, undefined), false)
})
